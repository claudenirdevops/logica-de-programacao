# Exercício 4: Contagem Regressiva para Lançamento
# Faça um programa que realize uma contagem regressiva de 10 até 1. Ao final do laço (fora
# dele), exiba a mensagem "Decolagem autorizada!".
# Conceito trabalhado: range(inicio, fim, passo) com passo negativo decrementando de 1 em 1.
# Nível 3: Iteração Direta sobre Strings (str)

for i in range(10, 0, -1):
    print(i)

print('Decolagem autorizada!')